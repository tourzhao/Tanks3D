constexpr bool classicStageLayoutsAreValid()
{
    for (const ClassicStageRows &stage : kClassicStageLayouts)
        for (std::string_view row : stage)
        {
            if (row.size() != kMapSize)
                return false;
            for (char tile : row)
                if (tile != '.' && tile != '#' && tile != '@' &&
                    tile != '%' && tile != '~' && tile != '-')
                    return false;
        }
    return true;
}

static_assert(classicStageLayoutsAreValid(),
              "classic stages must contain 26x26 supported terrain cells");
